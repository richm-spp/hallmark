#!/usr/bin/env node
/**
 * extract-theme-tokens.mjs — generate the per-theme token files the skill ships.
 *
 * The 21 themes' real values live in site/css/tokens.css, where Specimen doubles
 * as the `:root` base and every other theme overrides it. The skill never saw
 * that file (it isn't in the npm "files" list and nothing references it), so a
 * theme name reached the model with no values attached and the palette was
 * re-derived per run.
 *
 * Each emitted file is SELF-CONTAINED: base resolved + theme overrides applied,
 * as one `:root` block — an emitted page carries exactly one theme, so the
 * cascade that tokens.css needs for its live theme switcher is dead weight here.
 * Variant blocks (e.g. lumen's [data-drop="day"]) are appended verbatim.
 *
 *   node tools/build/extract-theme-tokens.mjs           # (re)generate
 *   node tools/build/extract-theme-tokens.mjs --check   # CI: fail on drift
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { parseCss } from '../verify/lib/css.mjs';

const ROOT = path.resolve(import.meta.dirname, '../..');
const SOURCE = 'site/css/tokens.css';
const OUT_DIR = 'skills/hallmark/references/themes/tokens';
const check = process.argv.includes('--check');

const css = readFileSync(path.join(ROOT, SOURCE), 'utf8').replace(/\r\n/g, '\n');
const rules = parseCss(css);

const themeName = (sel) => sel.match(/^\[data-theme="([a-z0-9-]+)"\]$/)?.[1] ?? null;
const anyThemeName = (sel) => sel.match(/\[data-theme="([a-z0-9-]+)"\]/)?.[1] ?? null;

// The base is whatever rule declares :root (Specimen shares that block).
const baseRule = rules.find((r) => r.selectors.some((s) => s === ':root'));
if (!baseRule) throw new Error(`${SOURCE}: no :root base block found`);

// Theme names, in first-appearance order.
const themes = [];
for (const rule of rules) {
  for (const sel of rule.selectors) {
    const name = themeName(sel);
    if (name && !themes.includes(name)) themes.push(name);
  }
}

const header = (theme) => `/*
  Hallmark theme tokens — ${theme}
  GENERATED by tools/build/extract-theme-tokens.mjs from ${SOURCE}.
  Do not edit by hand: edit the source, re-run the script.
  Self-contained: base tokens resolved, theme overrides applied.
*/
`;

function renderBlock(selector, decls) {
  const width = Math.max(...decls.map((d) => d.prop.length)) + 1;
  const lines = decls.map((d) => `  ${(d.prop + ':').padEnd(width)} ${d.value};`);
  return `${selector} {\n${lines.join('\n')}\n}\n`;
}

let drift = 0;
for (const theme of themes) {
  // Resolve: base first, then every plain [data-theme="X"] block in source order.
  const resolved = new Map();
  for (const d of baseRule.decls) resolved.set(d.prop, d.value);
  for (const rule of rules) {
    if (rule === baseRule) continue;
    if (!rule.selectors.some((s) => themeName(s) === theme)) continue;
    for (const d of rule.decls) resolved.set(d.prop, d.value);
  }

  let out = header(theme) + renderBlock(':root', [...resolved].map(([prop, value]) => ({ prop, value })));

  // Variant blocks (extra attributes) keep their original selectors.
  for (const rule of rules) {
    const variantSels = rule.selectors.filter((s) => anyThemeName(s) === theme && !themeName(s) && s !== ':root');
    if (variantSels.length) {
      out += `\n/* variant — preserved from ${SOURCE} */\n` + renderBlock(variantSels.join(',\n'), rule.decls);
    }
  }

  const file = path.join(ROOT, OUT_DIR, `${theme}.css`);
  if (check) {
    const current = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== out) {
      console.error(`drift: ${OUT_DIR}/${theme}.css ${current === null ? 'is missing' : `disagrees with ${SOURCE}`}`);
      drift++;
    }
  } else {
    mkdirSync(path.join(ROOT, OUT_DIR), { recursive: true });
    writeFileSync(file, out);
    console.log(`wrote ${OUT_DIR}/${theme}.css (${resolved.size} tokens)`);
  }
}

if (check) {
  if (drift) {
    console.error(`\ntokens: FAIL — ${drift} theme file(s) out of sync; run node tools/build/extract-theme-tokens.mjs`);
    process.exit(1);
  }
  console.log(`tokens: OK — ${themes.length} theme files in sync with ${SOURCE}`);
} else {
  console.log(`\n${themes.length} themes extracted`);
}
